import { readFile, writeFile, mkdir } from 'node:fs/promises';
const files = ['model', 'prompts', 'api', 'generation', 'ui'];
const modules = [];
for (const name of files) {
  const source = await readFile(new URL(`src/${name}.js`, import.meta.url), 'utf8');
  modules.push(source.replace(/^import .*;\n/gm, '').replace(/^export /gm, ''));
}
const css = await readFile(new URL('src/style.css', import.meta.url), 'utf8');
const js = `// Persona Adapter 1.3.1; generated by build.mjs.\n(() => {\n'use strict';\n${modules.join('\n')}\nmount(marinara, ${JSON.stringify(css)});\n})();\n`;
const config = { name: 'Persona Adapter', version: '1.3.1', description: 'Adapt a Persona to a selected Character while preserving editable Core Personality. Uses your Marinara LLM connection.', runtime: 'client', capabilities: ['full_page_access'] };
const out = new URL('dist/', import.meta.url); await mkdir(out, { recursive: true });
await writeFile(new URL('extension.js', out), js);
await writeFile(new URL('manifest.json', out), JSON.stringify({ kind: 'marinara.personal-extension', version: 1, config: { ...config, jsPath: 'extension.js' } }, null, 2));
await writeFile(new URL('persona-adapter.marinara-extension.json', out), JSON.stringify({ kind: 'marinara.personal-extension', version: 1, config: { ...config, js } }, null, 2));
console.log('Built dist/manifest.json, extension.js and single-file extension package.');
